    // ---- material helpers (Material and step sound of 1.5.2) ----

    /** Material.plants as BlockFlower: no collision, grass sound. */
    private static UnaryOperator<BlockBehaviour.Properties> plant(float hardness) {
        return p -> p.mapColor(MapColor.PLANT).noCollision().strength(hardness).sound(SoundType.GRASS).pushReaction(PushReaction.POPPED);
    }

    /** Material.wood; resistance as 1.5.2 explosion resistance (blockResistance / 5). */
    private static UnaryOperator<BlockBehaviour.Properties> wood(float hardness, float resistance) {
        return p -> p.mapColor(MapColor.SAND).instrument(NoteBlockInstrument.BASS).strength(hardness, resistance).sound(SoundType.WOOD)
                .ignitedByLava();
    }

    private static <B extends Block> DeferredBlock<B> block(String name, Function<BlockBehaviour.Properties, B> factory,
            UnaryOperator<BlockBehaviour.Properties> properties, UnaryOperator<Item.Properties> itemProperties) {
        DeferredBlock<B> block = BLOCKS.registerBlock(name, factory, properties);
        ITEMS.registerSimpleBlockItem(block, itemProperties);
        return block;
    }

    private static <B extends Block> DeferredBlock<B> block(String name, Function<BlockBehaviour.Properties, B> factory,
            UnaryOperator<BlockBehaviour.Properties> properties) {
        return block(name, factory, properties, p -> p);
    }

