package battletowers;

import battletowers.entity.BattleTowerGolem;
import battletowers.entity.GolemFireball;
import battletowers.gen.BTConfig;
import battletowers.gen.BTWorldGen;
import hexxit.worldgen152.OldGameIds;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.sounds.SoundEvent;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.MobCategory;
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.fml.common.Mod;
import net.neoforged.fml.loading.FMLEnvironment;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.entity.EntityAttributeCreationEvent;
import net.neoforged.neoforge.event.entity.player.PlayerInteractEvent;
import net.neoforged.neoforge.event.tick.ServerTickEvent;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * Battle Towers 1.3.4 for NeoForge: towers of spawners and chests generated by {@link BTWorldGen} in the 1.5.2 world
 * of worldgen152, the golem guarding each top floor with its fireballs, and the collapse of a tower whose golem died
 * ({@link TowerDestroyer}). Settings are the pack's config/BattleTowers.cfg (built into the jar).
 */
@Mod(BattleTowers.MOD_ID)
public final class BattleTowers {
    public static final String MOD_ID = "battletowers";

    private static final DeferredRegister.Entities ENTITIES = DeferredRegister.createEntities(MOD_ID);
    private static final DeferredRegister<SoundEvent> SOUNDS = DeferredRegister.create(Registries.SOUND_EVENT, MOD_ID);

    /** registerModEntity(..., 25, 5, true): 1.6 x 3.4, immune to fire. */
    public static final DeferredHolder<EntityType<?>, EntityType<BattleTowerGolem>> GOLEM = ENTITIES.registerEntityType("golem",
            BattleTowerGolem::new, MobCategory.MONSTER, b -> b.sized(1.6F, 3.4F).fireImmune().clientTrackingRange(2).updateInterval(5));
    public static final DeferredHolder<EntityType<?>, EntityType<GolemFireball>> GOLEM_FIREBALL = ENTITIES.registerEntityType("golem_fireball",
            GolemFireball::new, MobCategory.MISC, b -> b.noLootTable().sized(0.3F, 0.3F).clientTrackingRange(2).updateInterval(5));

    public static final DeferredHolder<SoundEvent, SoundEvent> GOLEM_LIVING = sound("golem");
    public static final DeferredHolder<SoundEvent, SoundEvent> GOLEM_AWAKEN = sound("golem_awaken");
    public static final DeferredHolder<SoundEvent, SoundEvent> GOLEM_CHARGE = sound("golem_charge");
    public static final DeferredHolder<SoundEvent, SoundEvent> GOLEM_DEATH = sound("golem_death");
    public static final DeferredHolder<SoundEvent, SoundEvent> GOLEM_HURT = sound("golem_hurt");
    public static final DeferredHolder<SoundEvent, SoundEvent> GOLEM_SPECIAL = sound("golem_special");
    public static final DeferredHolder<SoundEvent, SoundEvent> TOWER_BREAK_START = sound("tower_break_start");
    public static final DeferredHolder<SoundEvent, SoundEvent> TOWER_CRUMBLE = sound("tower_crumble");

    public BattleTowers(IEventBus modBus) {
        BTWorldGen.register();
        ENTITIES.register(modBus);
        SOUNDS.register(modBus);
        modBus.addListener(EntityAttributeCreationEvent.class, event -> event.put(GOLEM.get(), BattleTowerGolem.createAttributes().build()));
        // the golem of each tower type (AS_WorldGenTower spawned new AS_EntityGolem(world, towerType))
        for (int type = 0; type < 7; type++) {
            int towerType = type;
            OldGameIds.registerEntity(BTWorldGen.golemName(type), MOD_ID + ":golem", entity -> {
                if (entity instanceof BattleTowerGolem golem) {
                    golem.setTowerType(towerType);
                }
            });
        }
        NeoForge.EVENT_BUS.addListener(ServerTickEvent.Post.class, TowerDestroyer::tick);
        NeoForge.EVENT_BUS.addListener(PlayerInteractEvent.RightClickBlock.class, TowerEvents::onRightClickBlock);
        NeoForge.EVENT_BUS.addListener(PlayerInteractEvent.LeftClickBlock.class, TowerEvents::onLeftClickBlock);
        if (FMLEnvironment.getDist() == Dist.CLIENT) {
            battletowers.client.BTClient.register(modBus);
        }
    }

    public static BTConfig config() {
        return BTConfig.get();
    }

    private static DeferredHolder<SoundEvent, SoundEvent> sound(String name) {
        return SOUNDS.register(name, () -> SoundEvent.createVariableRangeEvent(Identifier.fromNamespaceAndPath(MOD_ID, name)));
    }
}
