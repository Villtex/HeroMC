    // ---- CoconutCraftingHandler and RawFiberCraftingHandler ----

    private static boolean isSword(ItemStack stack) {
        return stack.is(Items.WOODEN_SWORD) || stack.is(Items.STONE_SWORD) || stack.is(Items.IRON_SWORD) || stack.is(Items.GOLDEN_SWORD)
                || stack.is(Items.DIAMOND_SWORD);
    }

    private static void give(Player player, ItemStack stack) {
        player.getInventory().placeItemBackInInventory(stack, net.minecraft.util.Prediction.SERVER_ONLY);
    }

    /**
     * Fired before the grid is used up. Coconut seed from sword (top middle) over a coconut (centre) in a 3x3 grid: the
     * sword stays (one damage more), two milk fragments and two shells; the original put those into the grid slots left
     * and right of the coconut, here they go to the player (filling the grid would change the recipe being used up).
     * Leather from a single fur pelt: two raw fibers, likewise to the player.
     */
    private static void crafted(PlayerEvent.ItemCraftedEvent event) {
        ItemStack result = event.getCrafting();
        Container grid = event.getInventory();
        Player player = event.getEntity();
        boolean server = !player.level().isClientSide();
        if (result.is(COCONUT_SEED.get()) && grid.getContainerSize() > 4) {
            ItemStack sword = grid.getItem(1);
            ItemStack coconut = grid.getItem(4);
            if (isSword(sword) && coconut.is(COCONUT_ITEM.get())) {
                int damage = sword.getDamageValue() + 1;
                if (damage < sword.getMaxDamage()) {
                    sword.setDamageValue(damage);
                    sword.grow(1);
                }
                if (server) {
                    give(player, new ItemStack(COCONUT_MILK_FRAGMENT.get(), 2));
                    give(player, new ItemStack(COCONUT_SHELL.get(), 2));
                }
            }
        }
        if (result.is(Items.LEATHER)) {
            int pelts = 0;
            for (int i = 0; i < grid.getContainerSize(); i++) {
                ItemStack stack = grid.getItem(i);
                if (stack.isEmpty()) {
                    continue;
                }
                if (!stack.is(ZuluItems.FUR_PELT.get()) || pelts > 0) {
                    return;
                }
                pelts++;
            }
            if (pelts == 1 && server) {
                give(player, new ItemStack(ZuluItems.RAW_FIBER.get(), 2));
            }
        }
    }

    // ---- "Replace Default Flower Pot" = true ----

    /**
     * The pack replaced block 140 (the vanilla flower pot) by the universal flower pot. Blocks cannot be replaced
     * today, so the vanilla flower pot item places the universal pot instead (when it is used on a block that does
     * not take the click itself); the universal pot drops the vanilla item again.
     */
    private static void placeFlowerPot(UseItemOnBlockEvent event) {
        if (event.getUsePhase() != UseItemOnBlockEvent.UsePhase.ITEM_AFTER_BLOCK || !event.getItemStack().is(Items.FLOWER_POT)) {
            return;
        }
        BlockPlaceContext context = new BlockPlaceContext(event.getUseOnContext());
        if (!context.canPlace()) {
            return;
        }
        Level level = context.getLevel();
        BlockPos pos = context.getClickedPos();
        BlockState state = UNIVERSAL_FLOWER_POT.get().defaultBlockState();
        Player player = context.getPlayer();
        if (!state.canSurvive(level, pos) || !level.isUnobstructed(state, pos, player == null ? CollisionContext.empty()
                : CollisionContext.of(player))) {
            return;
        }
        if (!level.setBlock(pos, state, Block.UPDATE_ALL_IMMEDIATE)) {
            return;
        }
        SoundType sound = state.getSoundType(level, pos, player);
        level.playSound(player, pos, sound.getPlaceSound(), SoundSource.BLOCKS, (sound.getVolume() + 1.0F) / 2.0F, sound.getPitch() * 0.8F);
        level.gameEvent(GameEvent.BLOCK_PLACE, pos, GameEvent.Context.of(player, state));
        if (player == null || !player.getAbilities().instabuild) {
            event.getItemStack().shrink(1);
        }
        event.cancelWithResult(net.minecraft.world.InteractionResult.SUCCESS);
    }

    // ---- 1.5.2 ids -> block states (world generation of the World batch, old saplings) ----

    private static void registerOldBlocks() {
        OldBlockStates.registerMeta(ZuluIds.ALOE_VERA, meta -> ALOE_VERA.get().defaultBlockState().setValue(AloeVeraBlock.AGE, Math.min(meta, 8)));
        // BlockCocoa: bits 0-1 the side of the log (0 south, 1 west, 2 north, 3 east), bits 2-3 the age
        OldBlockStates.registerMeta(ZuluIds.COCONUT, meta -> COCONUT.get().defaultBlockState()
                .setValue(CocoaBlock.FACING, new Direction[] {Direction.SOUTH, Direction.WEST, Direction.NORTH, Direction.EAST}[meta & 3])
                .setValue(CocoaBlock.AGE, Math.min((meta & 12) >> 2, 2)));
        OldBlockStates.register(ZuluIds.CREEPER_BLOSSOM, () -> CREEPER_BLOSSOM.get().defaultBlockState());
        OldBlockStates.registerMeta(ZuluIds.NIGHT_BLOOM, meta -> NIGHT_BLOOM.get().defaultBlockState()
                .setValue(NightBloomBlock.STAGE, Math.min(meta, 4)));
        OldBlockStates.register(ZuluIds.PALM_TREE_DOUBLE_SLAB, () -> PALM_SLAB.get().defaultBlockState()
                .setValue(SlabBlock.TYPE, SlabType.DOUBLE));
        // bit 4 placed by a player, bit 8 decay check pending
        OldBlockStates.registerMeta(ZuluIds.PALM_TREE_LEAVES, meta -> PALM_LEAVES.get().defaultBlockState()
                .setValue(PalmLeavesBlock.PERSISTENT, (meta & 4) != 0)
                .setValue(PalmLeavesBlock.CHECK_DECAY, (meta & 8) != 0));
        // a plain block without orientation
        OldBlockStates.register(ZuluIds.PALM_TREE_LOG, () -> PALM_LOG.get().defaultBlockState().setValue(RotatedPillarBlock.AXIS, Direction.Axis.Y));
        OldBlockStates.register(ZuluIds.PALM_TREE_PLANK, () -> PALM_PLANKS.get().defaultBlockState());
        OldBlockStates.register(ZuluIds.PALM_TREE_SAPLING, () -> PALM_SAPLING.get().defaultBlockState());
        OldBlockStates.registerMeta(ZuluIds.PALM_TREE_SLAB, meta -> PALM_SLAB.get().defaultBlockState()
                .setValue(SlabBlock.TYPE, (meta & 8) != 0 ? SlabType.TOP : SlabType.BOTTOM));
        // BlockStairs: 0-3 the side the steps rise towards (east, west, south, north), bit 4 upside down
        OldBlockStates.registerMeta(ZuluIds.PALM_TREE_STAIRS, meta -> PALM_STAIRS.get().defaultBlockState()
                .setValue(BlockStateProperties.HORIZONTAL_FACING, new Direction[] {Direction.EAST, Direction.WEST, Direction.SOUTH, Direction.NORTH}[meta & 3])
                .setValue(BlockStateProperties.HALF, (meta & 4) != 0 ? Half.TOP : Half.BOTTOM));
        OldBlockStates.register(ZuluIds.QUICK_SAND, () -> QUICKSAND.get().defaultBlockState());
        OldBlockStates.register(ZuluIds.TUMBLEWEED, () -> TUMBLEWEED.get().defaultBlockState());
        OldBlockStates.register(ZuluIds.UNIVERSAL_FLOWER_POT, () -> UNIVERSAL_FLOWER_POT.get().defaultBlockState());
        OldBlockStates.registerMeta(ZuluIds.WATERED_DIRT, meta -> WateredDirtBlock.state(meta & 7));
    }

    public static void register(IEventBus modBus) {
        BLOCKS.register(modBus);
        ITEMS.register(modBus);
        ENTITIES.register(modBus);
        BLOCK_ENTITIES.register(modBus);
        registerOldBlocks();
        NeoForge.EVENT_BUS.addListener(ZuluPlants::crafted);
        NeoForge.EVENT_BUS.addListener(ZuluPlants::placeFlowerPot);
    }
